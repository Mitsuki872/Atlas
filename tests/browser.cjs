const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({permissions:['clipboard-read','clipboard-write']});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765');
 await page.getByRole('heading',{name:'Votre prospection, au même endroit.'}).waitFor();
 await page.getByRole('button',{name:'Nouvelle campagne'}).click();
 await page.locator('[name=name]').fill('QA navigateur — ne pas lancer');
 await page.getByRole('button',{name:'Enregistrer la campagne',exact:true}).click();
 await page.getByRole('heading',{name:'QA navigateur — ne pas lancer'}).waitFor();
 const diagnostics=await (await page.request.get('http://127.0.0.1:8765/api/diagnostics')).json();assert(diagnostics.data_directory.includes('prospect-browser-'),'Browser tests must use isolated data');
 const token=await page.evaluate(async()=> (await (await fetch('/api/session')).json()).token);
 const campaigns=await (await page.request.get('http://127.0.0.1:8765/api/campaigns')).json();
 const campaign=campaigns.find(c=>c.name==='QA navigateur — ne pas lancer');
 await page.getByRole('button',{name:'Modifier',exact:true}).click();
 await page.locator('[name=description]').fill('Validation réelle du formulaire');
 await page.getByRole('button',{name:'Enregistrer la campagne',exact:true}).click();
 await page.getByText('Validation réelle du formulaire',{exact:true}).waitFor();
 await page.locator('nav a[href="#prospects"]').click();
 await page.getByRole('button',{name:'Synthetic browser bakery',exact:true}).click();
 await page.locator('#company-form [name=status]').selectOption('À appeler');
 await page.getByRole('button',{name:'Enregistrer les corrections'}).click();
 await page.getByRole('status').filter({hasText:'Corrections enregistrées'}).waitFor();
 await page.getByRole('heading',{name:'Synthetic browser bakery'}).waitFor();
 await page.locator('#activity-form [name=text]').fill('Note de validation navigateur');
 await page.getByRole('button',{name:'Enregistrer l’activité'}).click();
 await page.locator('.activity').filter({hasText:'Note de validation navigateur'}).waitFor();
 await page.locator('#hours-form [name=day]').selectOption('0');
 await page.locator('#hours-form [name=type]').selectOption('call');
 await page.locator('#hours-form [name=start]').fill('14:00');
 await page.locator('#hours-form [name=end]').fill('15:00');
 await page.locator('#hours-form [name=source]').fill('https://example.com/fixture-call-hours');
 await page.getByRole('button',{name:'Ajouter cette plage sourcée'}).click();
 await page.getByRole('status').filter({hasText:'Plage sourcée enregistrée'}).waitFor();
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.getByRole('button',{name:'Importer JSON'}).click();
 await page.locator('input[type=file]').setInputFiles({name:'fixture.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify([{source_id:'browser-import',name:'Synthetic imported company',source_url:'https://example.com/fixture-import'}]))});
 await page.locator('[name=reuse]').check();
 await page.getByRole('button',{name:'Importer les entreprises'}).click();
 await page.getByRole('status').filter({hasText:'1 entreprises créées'}).waitFor();
 await page.locator('nav a[href="#planning"]').click();
 await page.getByRole('checkbox',{name:'Sélectionner Synthetic browser bakery'}).check();
 await page.getByRole('button',{name:'Prévisualiser le prompt ATLAS'}).click();
 await page.getByRole('heading',{name:'Prévisualisation ATLAS'}).waitFor();
 const prompt=await page.locator('#atlas-prompt').inputValue();assert(prompt.includes('Synthetic browser bakery'));assert(prompt.includes('Note de validation navigateur'));assert(prompt.includes('fixture-call-hours'));
 await page.getByRole('button',{name:'COPIER LE PROMPT POUR ATLAS'}).click();
 await page.getByRole('status').filter({hasText:'Prompt copié'}).waitFor();
 const clipboard=await page.evaluate(()=>navigator.clipboard.readText());assert.equal(clipboard,prompt);
 await page.getByRole('button',{name:'Fermer',exact:true}).click();
 await page.locator('nav a[href="#settings"]').click();
 await page.getByRole('button',{name:'Créer une sauvegarde'}).click();
 await page.getByRole('status').filter({hasText:'Sauvegarde créée'}).waitFor();
 await page.locator('nav a[href="#dashboard"]').click();
 await page.getByRole('heading',{name:'Votre prospection, au même endroit.'}).waitFor();
 await page.screenshot({path:'/tmp/prospect-dashboard.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/prospect-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 assert.deepEqual(errors,[]);
 console.log('PASS: campaign create/edit, CRM note/status, selection, ATLAS prompt, actual clipboard, sourced call hours, JSON import, backup, dashboard, mobile, no JS errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
